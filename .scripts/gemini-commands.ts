#!/usr/bin/env node
/**
 * Write a Gemini CLI wrapper for each om command (#356).
 *
 * Gemini reads custom commands only as TOML, from `.gemini/commands/`, so the
 * vault's `.claude/commands/om-*.md` don't exist there on their own. Each
 * wrapper's prompt injects its command file with `@{…}`, which Gemini resolves
 * from the workspace before it substitutes arguments, so the command text is
 * read live from the `.md` and there is no copy to drift. Wrappers for
 * commands that no longer exist are removed.
 *
 *   node --experimental-strip-types .scripts/gemini-commands.ts
 *
 * tests/gemini-commands.test.ts fails when a wrapper is missing or stale.
 */

import { mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { isMainModule } from "../.claude/scripts/lib/main-guard.ts";

/** The command's description: its frontmatter `description`, else its first line of prose. */
export function commandDescription(markdown: string): string {
	const front = /^---\r?\n([\s\S]*?)\r?\n---/.exec(markdown)?.[1] ?? "";
	const line = /^description:\s*(.*)$/m.exec(front)?.[1]?.trim() ?? "";
	if (line) {
		try {
			return line.startsWith('"') ? (JSON.parse(line) as string) : line;
		} catch {
			return line.replace(/^["']|["']$/g, "");
		}
	}
	const body = markdown.replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n/, "");
	return body.split(/\r?\n/).map((l) => l.trim()).find((l) => l !== "" && !l.startsWith("#")) ?? "";
}

/** The Gemini TOML wrapper for the om command `name`, given its markdown. */
export function geminiCommand(name: string, markdown: string): string {
	return [
		`# Generated by .scripts/gemini-commands.ts from .claude/commands/${name}.md. Do not edit: run the script.`,
		`description = ${JSON.stringify(commandDescription(markdown))}`,
		'prompt = """',
		`Run the vault command below. It is written for Claude Code: where it says $ARGUMENTS, use these arguments: {{args}}`,
		"",
		`@{.claude/commands/${name}.md}`,
		'"""',
		"",
	].join("\n");
}

function main(): void {
	const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
	const commands = join(repo, ".claude", "commands");
	const wrappers = join(repo, ".gemini", "commands");
	mkdirSync(wrappers, { recursive: true });
	const names = readdirSync(commands)
		.filter((f) => /^om-.+\.md$/.test(f))
		.map((f) => f.replace(/\.md$/, ""));
	for (const name of names) {
		writeFileSync(join(wrappers, `${name}.toml`), geminiCommand(name, readFileSync(join(commands, `${name}.md`), "utf8")));
	}
	for (const file of readdirSync(wrappers).filter((f) => /^om-.+\.toml$/.test(f))) {
		if (!names.includes(file.replace(/\.toml$/, ""))) unlinkSync(join(wrappers, file));
	}
	console.log(`${names.length} Gemini command wrappers in .gemini/commands/`);
}

if (isMainModule(import.meta.url)) main();
